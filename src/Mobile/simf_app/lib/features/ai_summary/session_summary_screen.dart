/// The three tabs (frame `1072:14647`): active = gold fill, others = beige
/// hairline. Order (reading) speakers · key-points · recommendations.
class _Tabs extends StatelessWidget {
  const _Tabs({required this.active, required this.l10n, required this.onChanged});

  final _SummaryTab active;
  final AppL10n l10n;
  final ValueChanged<_SummaryTab> onChanged;

  @override
  Widget build(BuildContext context) {
    final tabs = <(_SummaryTab, String)>[
      (_SummaryTab.speakers, l10n.aiSummarySpeakersHeading),
      (_SummaryTab.keyPoints, l10n.aiSummaryKeyPointsHeading),
      (_SummaryTab.recommendations, l10n.aiSummaryRecommendationsHeading),
    ];
    return Row(
      children: <Widget>[
        for (final (index, (tab, label)) in tabs.indexed) ...<Widget>[
          if (index > 0) const SizedBox(width: SimfTokens.space2),
          Expanded(
            child: _PillButton(
              label: label,
              filled: tab == active,
              fontWeight:
                  tab == active ? FontWeight.w700 : FontWeight.w500,
              onTap: () => onChanged(tab),
            ),
          ),
        ],
      ],
    );
  }
}

