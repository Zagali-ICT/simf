/// Locale-data-free formatters (mirror `sessions_screen.dart`).
final DateFormat _time24 = DateFormat('HH:mm'); // 09:30
final DateFormat _timeRow = DateFormat('hh:mm a'); // 08:00 PM

const List<String> _weekdaysAr = <String>[
  'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت', 'الأحد',
];
const List<String> _weekdaysEn = <String>[
  'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday',
];

String _weekday(DateTime d, bool isArabic) =>
    (isArabic ? _weekdaysAr : _weekdaysEn)[d.weekday - 1];

/// The three summary tabs (frame `1072:14647`).
enum _SummaryTab { speakers, keyPoints, recommendations }

/// Page 034 — ملخص الجلسة · AI session summary (#34, `/ai-summary`).
///
/// **Public** (Guest+, `AllowAnonymous`). Pixel-parity to KSA Figma frame
/// `1072:13518`: the navy [KsaPage] shell, the "اختر الجلسة" session picker
/// (reuses the programme list), the "generated by AI" banner, the
/// المتحدثون / أبرز النقاط / التوصيات tabs (mapped to the published summary's
/// `speakers` / `keyPoints` / `recommendations`) and the
/// النص الكامل / مشاركة / حفظ action row. Opened with an optional `sessionId`
/// (preselected); otherwise the first programme session is selected. Reads the
/// published summary (`GET /app/programme/sessions/{id}/summary`); a 404 means
/// the session has no published summary yet.
class AiSummaryScreen extends ConsumerStatefulWidget {
  const AiSummaryScreen({this.sessionId, super.key});

  final String? sessionId;

  @override
  ConsumerState<AiSummaryScreen> createState() => _AiSummaryScreenState();
}

class _AiSummaryScreenState extends ConsumerState<AiSummaryScreen> {
  String? _selectedId;
  SessionListItem? _selectedSession;
  bool _loading = false;
  bool _error = false;
  bool _notFound = false;
  SessionSummary? _summary;
  _SummaryTab _tab = _SummaryTab.keyPoints;

  @override
  void initState() {
    super.initState();
    final id = widget.sessionId?.trim();
    if (id != null && id.isNotEmpty) {
      _selectedId = id;
      unawaited(_load());
    }
  }

  Future<void> _load() async {
    final id = _selectedId;
    if (id == null) {
      return;
    }
    setState(() {
      _loading = true;
      _error = false;
      _notFound = false;
    });
    try {
      final summary =
          await ref.read(sessionSummaryRepositoryProvider).getSummary(id);
      if (!mounted) {
        return;
      }
      setState(() {
        _summary = summary;
        _loading = false;
      });
    } on ApiFailure catch (failure) {
      if (!mounted) {
        return;
      }
      setState(() {
        _loading = false;
        _notFound = failure.httpStatus == 404;
        _error = failure.httpStatus != 404;
      });
    }
  }

  void _select(SessionListItem session) {
    if (session.id == _selectedId && _selectedSession != null) {
      return;
    }
    setState(() {
      _selectedId = session.id;
      _selectedSession = session;
    });
    unawaited(_load());
  }

  /// Preselect on first session load: the passed-in id (resolving its item) or
  /// the first session. Guarded so it only fires until a selection is resolved.
  void _ensureSelection(List<SessionListItem> sessions) {
    if (sessions.isEmpty || (_selectedId != null && _selectedSession != null)) {
      return;
    }
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!mounted) {
        return;
      }
      if (_selectedId == null) {
        _select(sessions.first);
      } else if (_selectedSession == null) {
        final match = sessions.where((s) => s.id == _selectedId);
        if (match.isNotEmpty) {
          setState(() => _selectedSession = match.first);
        }
      }
    });
  }

  Future<void> _share(SessionSummary summary, bool isArabic) async {
    final text = <String>[
      if (_selectedSession != null) _selectedSession!.localizedTitle(isArabic),
      summary.localizedKeyPoints(isArabic),
      summary.localizedRecommendations(isArabic),
    ].where((p) => p.trim().isNotEmpty).join('\n\n');
    if (text.isEmpty) {
      return;
    }
    try {
      await Share.share(text);
    } catch (_) {
      // Sharing is best-effort (no share target / cancelled) — ignore.
    }
  }

  void _save(AppL10n l10n) {
    ScaffoldMessenger.of(context)
      ..hideCurrentSnackBar()
      ..showSnackBar(SnackBar(content: Text(l10n.aiSummarySaved)));
  }

  void _showFullText(AppL10n l10n, String text) {
    showModalBottomSheet<void>(
      context: context,
      backgroundColor: SimfTokens.navyDeep,
      showDragHandle: true,
      isScrollControlled: true,
      builder: (_) => SafeArea(
        child: Padding(
          padding: const EdgeInsets.fromLTRB(
            SimfTokens.space4,
            0,
            SimfTokens.space4,
            SimfTokens.space6,
          ),
          child: SingleChildScrollView(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: <Widget>[
                _SectionHeading(l10n.aiSummaryFullTextHeading),
                const SizedBox(height: SimfTokens.space3),
                Text(
                  text.trim().isEmpty ? l10n.aiSummaryNone : text,
                  style: const TextStyle(
                    color: SimfTokens.txtSecondary,
                    height: 1.75,
                    fontSize: SimfTokens.textSm,
                  ),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final l10n = AppL10n.of(context);
    final sessions = ref.watch(aiSummarySessionsProvider);
    return KsaPage(
      title: l10n.aiSummaryTitle,
      onBack: () => ksaBackOrHome(context),
      body: ListView(
        padding: const EdgeInsets.all(SimfTokens.space4),
        children: <Widget>[
          sessions.when(
            loading: () => const _PickerLoading(),
            error: (_, __) => _Inline(
              icon: Icons.event_busy_outlined,
              message: l10n.aiSummaryNoSessions,
            ),
            data: (list) {
              if (list.isEmpty) {
                return _Inline(
                  icon: Icons.event_busy_outlined,
                  message: l10n.aiSummaryNoSessions,
                );
              }
              _ensureSelection(list);
              return _SessionPicker(
                title: l10n.aiSummaryChooseSession,
                sessions: list,
                selectedId: _selectedId,
                isArabic: l10n.isArabic,
                onSelect: _select,
              );
            },
          ),
          const SizedBox(height: SimfTokens.space4),
          ..._summaryArea(l10n),
        ],
      ),
    );
  }

  List<Widget> _summaryArea(AppL10n l10n) {
    if (_selectedId == null) {
      return const <Widget>[];
    }
    if (_loading) {
      return const <Widget>[
        Padding(
          padding: EdgeInsets.symmetric(vertical: SimfTokens.space8),
          child: Center(child: CircularProgressIndicator()),
        ),
      ];
    }
    if (_notFound) {
      return <Widget>[
        _Inline(icon: Icons.summarize_outlined, message: l10n.aiSummaryNone),
      ];
    }
    if (_error || _summary == null) {
      return <Widget>[
        _ErrorInline(
          message: l10n.aiSummaryError,
          onRetry: () => unawaited(_load()),
        ),
      ];
    }
    return _content(l10n, _summary!);
  }

  List<Widget> _content(AppL10n l10n, SessionSummary summary) {
    final isArabic = l10n.isArabic;
    final session = _selectedSession;
    final block = switch (_tab) {
      _SummaryTab.speakers => summary.localizedSpeakers(isArabic),
      _SummaryTab.keyPoints => summary.localizedKeyPoints(isArabic),
      _SummaryTab.recommendations => summary.localizedRecommendations(isArabic),
    };
    final tabTitle = switch (_tab) {
      _SummaryTab.speakers => l10n.aiSummarySpeakersHeading,
      _SummaryTab.keyPoints => l10n.aiSummaryKeyPointsHeading,
      _SummaryTab.recommendations => l10n.aiSummaryRecommendationsHeading,
    };
    return <Widget>[
      if (summary.generatedByAi) ...<Widget>[
        _AiBanner(
          label: l10n.aiSummaryGeneratedBanner,
          subtitle: session == null
              ? null
              : '${session.localizedTitle(isArabic)} · '
                  '${_time24.format(session.startLocal)}',
        ),
        const SizedBox(height: SimfTokens.space4),
      ],
      _Tabs(active: _tab, l10n: l10n, onChanged: (t) => setState(() => _tab = t)),
      const SizedBox(height: SimfTokens.space4),
      _ContentCard(title: tabTitle, block: block, emptyLabel: l10n.aiSummaryNone),
      const SizedBox(height: SimfTokens.space4),
      _ActionRow(
        l10n: l10n,
        onFullText: () =>
            _showFullText(l10n, summary.localizedFullText(isArabic)),
        onShare: () => unawaited(_share(summary, isArabic)),
        onSave: () => _save(l10n),
      ),
    ];
  }
}

/// The "اختر الجلسة" picker (frame `1072:14628`): the title, a bordered
/// selected-session box (with the collapse chevron) and, when expanded, the
/// tappable session list.
class _SessionPicker extends StatefulWidget {
  const _SessionPicker({
    required this.title,
    required this.sessions,
    required this.selectedId,
    required this.isArabic,
    required this.onSelect,
  });

  final String title;
  final List<SessionListItem> sessions;
  final String? selectedId;
  final bool isArabic;
  final ValueChanged<SessionListItem> onSelect;

  @override
  State<_SessionPicker> createState() => _SessionPickerState();
}

class _SessionPickerState extends State<_SessionPicker> {
  bool _expanded = true;

  @override
  Widget build(BuildContext context) {
    final sessions = widget.sessions;
    final selected = sessions.where((s) => s.id == widget.selectedId);
    final current = selected.isNotEmpty ? selected.first : null;
    return Container(
      padding: const EdgeInsets.all(SimfTokens.space4),
      decoration: BoxDecoration(
        color: SimfTokens.navyDeep,
        borderRadius: BorderRadius.circular(SimfTokens.radius),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: <Widget>[
          Text(
            widget.title,
            style: const TextStyle(
              color: Colors.white,
              fontSize: SimfTokens.textLg,
              fontWeight: FontWeight.w500,
            ),
          ),
          const SizedBox(height: SimfTokens.space3),
          if (current != null)
            _SelectedSessionBox(
              session: current,
              isArabic: widget.isArabic,
              expanded: _expanded,
              onToggle: () => setState(() => _expanded = !_expanded),
            ),
          if (_expanded) ...<Widget>[
            const SizedBox(height: SimfTokens.space2),
            for (final session in sessions)
              _SessionRow(
                session: session,
                selected: session.id == widget.selectedId,
                isArabic: widget.isArabic,
                onTap: () => widget.onSelect(session),
              ),
          ],
        ],
      ),
    );
  }
}

/// The highlighted selected-session box (frame `1072:14603`): beige hairline,
/// the collapse chevron, the gold title and the day · time · hall sub-line.
